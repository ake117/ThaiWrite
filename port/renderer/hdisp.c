/* --- thaikey: ASCII อังกฤษ -> ไทย (แป้นเกษมณี) ------------------------ */
int thaikey(int key)
{
    unsigned int al = (unsigned int)key & 0xffu;

    if (al < (unsigned int)(sizeof kesmanee_table))
    {
        return (int)(((unsigned int)key & 0xff00u) |
                     (unsigned int)kesmanee_table[al]);
    }
    return key;
}

/* --- stdtoku: standard (TIS-620) -> KU code -------------------------- */
char stdtoku(char c)
{
    unsigned char a = (unsigned char)c;

    if (a < 0x80)
    {
        return (char)a;
    }
    return (char)std_to_ku[a - 0x80];
}

/* --- kutostd: KU code -> standard (TIS-620) -------------------------- */
char kutostd(char c)
{
    unsigned char a = (unsigned char)c;

    if (a < 0x80)
    {
        return (char)a;
    }
    return (char)ku_to_std[a - 0x80];
}
